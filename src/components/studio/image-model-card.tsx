"use client";

import { useEffect, useState } from "react";
import { Cpu } from "lucide-react";
import { api, ApiError } from "@/lib/api/client";
import { cn } from "@/lib/cn";
import type { ImageModelState, ImageModelStatus } from "@/types/api";
import { FieldLegend } from "./option-group";

const STATE_LABEL: Record<ImageModelState, { label: string; tone: string }> = {
  loaded: { label: "Loaded", tone: "bg-emerald-400" },
  not_loaded: { label: "Ready · loads on first image", tone: "bg-emerald-400/60" },
  loading: { label: "Loading…", tone: "bg-amber-300 animate-pulse" },
  not_downloaded: { label: "Weights not downloaded", tone: "bg-amber-300" },
  unavailable: { label: "AI libraries not installed", tone: "bg-red-400" },
  error: { label: "Failed to load", tone: "bg-red-400" },
  disabled: { label: "Generation turned off", tone: "bg-fg-subtle" },
};

type CardState = { kind: "loading" } | { kind: "ok"; status: ImageModelStatus } | { kind: "offline"; message: string };

/** Shows the real local model and its state. Fetching status never loads the model. */
export function ImageModelCard({ refreshKey = 0 }: { refreshKey?: string | number }) {
  const [state, setState] = useState<CardState>({ kind: "loading" });

  useEffect(() => {
    let cancelled = false;
    api
      .imageModel()
      .then((status) => !cancelled && setState({ kind: "ok", status }))
      .catch((err: unknown) => {
        if (cancelled) return;
        setState({ kind: "offline", message: err instanceof ApiError ? err.message : "Couldn't reach the backend." });
      });
    return () => {
      cancelled = true;
    };
  }, [refreshKey]);

  return (
    <fieldset>
      <FieldLegend hint="Images are generated by an open-weight model running on your own backend. No paid or remote API is used.">
        Model
      </FieldLegend>
      <div className="flex items-start gap-3 rounded-lg border border-line bg-ink-900 p-3" aria-live="polite">
        <span className="grid size-8 shrink-0 place-items-center rounded-md border border-line-strong bg-ink-800 text-violet-soft">
          <Cpu className="size-4" aria-hidden />
        </span>
        <div className="min-w-0 flex-1 text-sm">
          {state.kind === "loading" && <p className="text-fg-muted">Checking model…</p>}
          {state.kind === "offline" && (
            <>
              <p className="text-fg">Backend unreachable</p>
              <p className="mt-0.5 text-xs text-fg-muted">{state.message}</p>
            </>
          )}
          {state.kind === "ok" && (
            <>
              <p className="truncate font-mono text-[13px] text-fg">{state.status.model_id ?? "No model"}</p>
              <p className="mt-1 flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-fg-muted">
                <span className="flex items-center gap-1.5">
                  <span aria-hidden className={cn("size-1.5 rounded-full", STATE_LABEL[state.status.state].tone)} />
                  {STATE_LABEL[state.status.state].label}
                </span>
                {state.status.device && <span className="font-mono uppercase">· {state.status.device}</span>}
              </p>
              {!state.status.can_generate && state.status.state !== "disabled" && (
                <p className="mt-2 text-xs leading-relaxed text-fg-muted">{state.status.detail}</p>
              )}
              {state.status.state === "not_downloaded" && (
                <p className="mt-2 text-xs leading-relaxed text-fg-muted">
                  In <code className="font-mono text-[11px] text-fg">backend/</code>, run{" "}
                  <code className="rounded bg-ink-800 px-1 py-0.5 font-mono text-[11px] text-fg">
                    python scripts/download_model.py
                  </code>{" "}
                  once (needs internet).
                </p>
              )}
            </>
          )}
        </div>
      </div>
    </fieldset>
  );
}
